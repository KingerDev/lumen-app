/**
 * UI strings in Slovak and English.
 *
 * The language is read once at launch from the phone's preferred-language list:
 * the first of them Lumen speaks wins, English otherwise. iOS restarts the app
 * when that list changes, so nothing here has to react to it at runtime.
 *
 * Strings that take a value are functions, so the plural rules of each language
 * live next to its wording instead of in the screens.
 */

export type Lang = 'sk' | 'en';

function detectLang(): Lang {
  for (const locale of getLocales()) {
    if (locale.languageCode === 'sk') return 'sk';
    if (locale.languageCode === 'en') return 'en';
  }
  return 'en';
}

